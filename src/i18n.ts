export const DICTS: Record<Lang, Dict> = { el, en };

export function tr(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.el[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

export function money(lang: Lang, n: number): string {
  return new Intl.NumberFormat(lang === 'el' ? 'el-GR' : 'en-IE', {
    style: 'currency', currency: 'EUR', maximumFractionDigits: 0,
  }).format(n);
}
